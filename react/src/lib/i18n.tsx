const TRANSLATIONS: Record<Language, Translations> = { es, en, fr };

// ── Context ───────────────────────────────────────────────────────────────────

interface I18nContextValue {
  lang: Language;
  region: Region;
  regionConfig: RegionConfig;
  setLang: (l: Language) => void;
  setRegion: (r: Region) => void;
  t: (key: keyof Translations) => string;
  formatCurrency: (amount: number, currency?: string) => string;
  formatDate: (dateStr: string | null | undefined) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

const STORAGE_LANG_KEY = 'app_language';
const STORAGE_REGION_KEY = 'app_region';

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Language>(() => {
    const saved = localStorage.getItem(STORAGE_LANG_KEY);
    return (saved as Language) || 'es';
  });
  const [region, setRegionState] = useState<Region>(() => {
    const saved = localStorage.getItem(STORAGE_REGION_KEY);
    return (saved as Region) || 'DO';
  });

  const regionConfig = REGIONS[region];

  function setLang(l: Language) {
    setLangState(l);
    localStorage.setItem(STORAGE_LANG_KEY, l);
  }

  function setRegion(r: Region) {
    setRegionState(r);
    localStorage.setItem(STORAGE_REGION_KEY, r);
  }

  function t(key: keyof Translations): string {
    return TRANSLATIONS[lang][key] ?? TRANSLATIONS['es'][key] ?? key;
  }

  function formatCurrency(amount: number, currency?: string): string {
    const cur = currency || regionConfig.currency;
    return new Intl.NumberFormat(regionConfig.locale, {
      style: 'currency',
      currency: cur,
      minimumFractionDigits: 2,
    }).format(amount);
  }

  function formatDate(dateStr: string | null | undefined): string {
    if (!dateStr) return '-';
    return new Date(dateStr + 'T00:00:00').toLocaleDateString(regionConfig.locale, {
      year: 'numeric',
      month: 'short',
      day: '2-digit',
    });
  }

  return (
    <I18nContext.Provider value={{ lang, region, regionConfig, setLang, setRegion, t, formatCurrency, formatDate }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider');
  return ctx;
}
