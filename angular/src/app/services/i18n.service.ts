@Injectable({ providedIn: 'root' })
export class I18nService {
  private readonly LANG_KEY = 'facturapro_lang';
  private readonly REGION_KEY = 'facturapro_region';

  lang = signal<Lang>((localStorage.getItem(this.LANG_KEY) as Lang) || 'es');
  region = signal<Region>((localStorage.getItem(this.REGION_KEY) as Region) || 'DO');
  regionConfig = computed(() => REGIONS[this.region()]);

  t(key: string): string {
    return translations[this.lang()][key] ?? translations['es'][key] ?? key;
  }

  setLang(l: Lang) { this.lang.set(l); localStorage.setItem(this.LANG_KEY, l); }
  setRegion(r: Region) { this.region.set(r); localStorage.setItem(this.REGION_KEY, r); }

  formatCurrency(amount: number, currency?: string): string {
    const cfg = this.regionConfig();
    const cur = currency || cfg.currency;
    return new Intl.NumberFormat('en-US', { style: 'currency', currency: cur, minimumFractionDigits: 2 }).format(amount);
  }

  formatDate(dateStr: string): string {
    if (!dateStr) return '';
    try { return new Date(dateStr).toLocaleDateString(); } catch { return dateStr; }
  }
}
